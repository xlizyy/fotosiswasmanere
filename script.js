        chatToggle.addEventListener('click', () => {
            chatWindow.classList.toggle('hidden');
            chatWindow.classList.toggle('animate-pop-in');
        });
        chatClose.addEventListener('click', () => {
            chatWindow.classList.add('hidden');
            chatWindow.classList.remove('animate-pop-in');
        });

        chatForm.addEventListener('submit', (e) => {
            e.preventDefault();
            const userInput = chatInput.value.trim().toLowerCase();
            if (!userInput) return;

            handleUserQuery(userInput);
            chatInput.value = '';
        });

        quickRepliesContainer.querySelectorAll('.quick-reply-btn').forEach(button => {
            button.addEventListener('click', () => {
                const question = button.textContent.toLowerCase();
                handleUserQuery(question);
            });
        });

        function handleUserQuery(query) {
             addChatMessage(query, 'user');
             quickRepliesContainer.style.display = 'none'; // Hide buttons after selection
            
            setTimeout(() => {
                let botReply = botResponses.default;
                if (query.includes("tidak ditemukan") || query.includes("tidak ada")) {
                    botReply = botResponses["tidak ditemukan"];
                } else if (query.includes("ikut sesi foto") || query.includes("mengikuti sesi foto")) {
                    botReply = botResponses["mengikuti sesi foto"];
                }
                addChatMessage(botReply, 'bot');
            }, 1000);
        }

        function addChatMessage(message, sender) {
            const messageWrapper = document.createElement('div');
            messageWrapper.className = `flex ${sender === 'user' ? 'justify-end' : 'justify-start'}`;
            
            const messageBubble = document.createElement('p');
            // Use original casing for user messages
            const displayMessage = sender === 'user' ? (message.charAt(0).toUpperCase() + message.slice(1)).replace(' ikut sesi foto ', ' mengikuti sesi foto ') : message;
            messageBubble.className = `p-3 rounded-lg max-w-xs ${sender === 'user' ? 'bg-pink-600 text-white' : 'bg-gray-700 text-white'}`;
            messageBubble.textContent = displayMessage;

            messageWrapper.appendChild(messageBubble);
            chatMessages.appendChild(messageWrapper);
            chatMessages.scrollTop = chatMessages.scrollHeight;
        }

