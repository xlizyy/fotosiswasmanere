        const form = document.getElementById('photo-form');
        const nisInput = document.getElementById('nis-input');
        const notificationArea = document.getElementById('notification-area');

        form.addEventListener('submit', function(event) {
            event.preventDefault();
            const nis = nisInput.value.trim();
            
            notificationArea.innerHTML = '';
            notificationArea.className = 'mt-6 min-h-[50px] flex items-center justify-center';

            if (!nis) {
                displayMessage('Mohon masukkan Nomor Induk Siswa Anda.', 'error');
                return;
            }

            if (studentPhotoLinks.hasOwnProperty(nis)) {
                const link = studentPhotoLinks[nis];
                
                // Check if the link exists and is not empty
                if (link) {
                    const successMessage = `
                        <p class="font-bold">Foto Anda Berhasil Ditemukan!</p>
                        <a href="${link}" target="_blank" rel="noopener noreferrer" class="mt-2 inline-block bg-gradient-to-r from-green-400 to-teal-500 text-white font-bold py-2 px-6 rounded-lg hover:from-green-500 hover:to-teal-600 transition-transform transform hover:scale-105 shadow-lg">
                            Unduh Foto Anda
                        </a>
                    `;
                    displayMessage(successMessage, 'success');
                } else {
                    // Handle case where NIS is found but the link is empty
                    displayMessage('Foto Anda tidak ditemukan.', 'error');
                }
            } else {
                displayMessage('Nomor Induk Siswa tidak ditemukan. Silakan periksa kembali.', 'error');
            }

            nisInput.value = '';
        });
        
        /**
         * Displays a message in the notification area.
         * @param {string} htmlContent - The HTML content of the message to display.
         * @param {string} type - The type of message ('success' or 'error').
         */
        function displayMessage(htmlContent, type) {
            const messageContainer = document.createElement('div');
            messageContainer.className = `p-4 rounded-xl w-full animate-pop-in backdrop-blur-sm`;
            
            if (type === 'success') {
                messageContainer.classList.add('bg-green-500/20', 'text-green-300');
            } else { // error
                messageContainer.classList.add('bg-red-500/20', 'text-red-300');
            }
            
            messageContainer.innerHTML = htmlContent;
            notificationArea.appendChild(messageContainer);

            // Automatically remove the notification after 15 seconds
            setTimeout(() => {
                messageContainer.classList.remove('animate-pop-in');
                messageContainer.classList.add('animate-fade-out');
                
                // Remove the element from the DOM after the animation finishes
                setTimeout(() => {
                    if (notificationArea.contains(messageContainer)) {
                        notificationArea.removeChild(messageContainer);
                    }
                }, 500); // Duration should match the CSS animation
            }, 7000); // 15 seconds
        }
        
